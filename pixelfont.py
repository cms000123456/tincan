ROWS = 9
GAP = 1          # glyph spacing in font pixels
LEADING = 2      # extra rows between lines

# Masks as lists of (x, y) on-pixels, plus width, built once.
_GLYPHS = {}
for _k, _rows in _G.items():
    assert len(_rows) == ROWS, _k
    _w = len(_rows[0])
    assert all(len(r) == _w for r in _rows), _k
    _GLYPHS[_k] = (_w, [(x, y) for y, r in enumerate(_rows)
                        for x, c in enumerate(r) if c == "#"])
_FALLBACK = _GLYPHS["?"]


def scale_for(size):
    """Map a nominal TTF point size to an integer pixel scale."""
    if size < 15:
        return 1
    if size < 28:
        return 2
    return max(3, round(size / 10))


class PixelFont:
    def __init__(self, size, bold=False):
        self.scale = scale_for(size)
        self.bold = bold
        self._cache = {}

    # pygame.font.Font API subset ------------------------------------------
    def set_bold(self, b):
        self.bold = bool(b)
        self._cache.clear()

    def get_height(self):
        return ROWS * self.scale

    def get_linesize(self):
        return (ROWS + LEADING) * self.scale

    def _bold_px(self):
        # bold thickens strokes by a fraction of a font pixel, so counters
        # in m/w/e stay open (a full-pixel smear fills them in)
        return max(1, self.scale // 3) if self.bold else 0

    def size(self, txt):
        if not txt:
            return (0, self.get_height())
        cols = sum(_GLYPHS.get(c, _FALLBACK)[0] + GAP for c in txt) - GAP
        return (cols * self.scale + self._bold_px(), self.get_height())

    def render(self, txt, antialias=False, color=(255, 255, 255), bg=None):
        key = (txt, tuple(color))
        img = self._cache.get(key)
        if img is not None:
            return img
        s = self.scale
        w, h = self.size(txt)
        img = pygame.Surface((max(1, w), h), pygame.SRCALPHA)
        x = 0
        for ch in txt:
            gw, pix = _GLYPHS.get(ch, _FALLBACK)
            for px, py in pix:
                img.fill(color, ((x + px) * s, py * s, s, s))
                if self.bold:
                    img.fill(color, ((x + px) * s + self._bold_px(), py * s,
                                     s, s))
            x += gw + GAP
        if len(self._cache) > 512:
            self._cache.clear()
        self._cache[key] = img
        return img
